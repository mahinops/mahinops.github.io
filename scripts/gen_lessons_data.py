#!/usr/bin/env python3
"""Generate _data/lessons.yml from the lesson index in go-go-go/index.html.

Run from the repo root (scripts/sync-lessons.sh does this for you).
"""
import html
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
index = (root / "go-go-go" / "index.html").read_text(encoding="utf-8")
tile = re.compile(r'<a class="tile" href="((?:go|dsa)/[^"]+)"><b>\d+\.\s*(.*?)</b><span>(.*?)</span></a>', re.S)

groups = {"go": [], "dsa": []}
for href, title, desc in tile.findall(index):
    groups[href.split("/")[0]].append((href, html.unescape(title), html.unescape(desc)))

if not groups["go"] or not groups["dsa"]:
    sys.exit("no lessons found in go-go-go/index.html; is the folder in sync?")


def quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = ["# Generated by scripts/gen_lessons_data.py. Do not edit by hand.\n"]
for key in ("go", "dsa"):
    out.append(f"{key}:\n")
    for href, title, desc in groups[key]:
        out.append(f"  - title: {quote(title)}\n    desc: {quote(desc)}\n    href: {quote(href)}\n")
(root / "_data" / "lessons.yml").write_text("".join(out), encoding="utf-8")
print(f"wrote _data/lessons.yml: {len(groups['go'])} Go + {len(groups['dsa'])} DSA lessons")
